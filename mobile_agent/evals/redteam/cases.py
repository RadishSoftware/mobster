def _return(id, app, composer, title_bar, quote, other, *, placeholder="", role="TextView", label=None,
            act="send_message"):
    elements = (bar(title_bar), BACK, el("hey", "StaticText", (.05, .3, .6, .05)),
                el(label if label is not None else composer, role, (.05, .88, .9, .05), placeholder=placeholder))
    screen = Screen("chat", app[0], elements)
    target = label if label is not None else composer
    return Case(id, "keyboard", app, (screen,), (("TYPE_SUBMIT", target, "On my way"),),
                frozenset({("TYPE_SUBMIT", target)}), asked=quote, other=other,
                items=(commit(act, f"message to {title_bar}", quote, app[1]),), title=r"send|message|reply|post")


