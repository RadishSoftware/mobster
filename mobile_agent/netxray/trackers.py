# Not the Public Suffix List: a short list keeps the dependency out, and a miss only shows a longer domain.
MULTI_SUFFIXES = {
    "co.uk", "org.uk", "ac.uk", "gov.uk", "com.au", "net.au", "org.au", "co.nz", "co.jp", "ne.jp", "or.jp",
    "co.kr", "or.kr", "com.br", "com.cn", "net.cn", "com.hk", "com.tw", "com.sg", "com.my", "co.in", "co.id",
    "com.mx", "com.ar", "com.tr", "co.za", "com.ua", "co.il", "com.vn", "com.ph", "com.sa", "com.eg", "com.pk",
    "com.co", "com.pe", "com.ng", "co.th", "in.th",
    # Hosting suffixes where every customer gets a name: the customer's label is the registrable part.
    "appspot.com", "herokuapp.com", "github.io", "vercel.app", "netlify.app", "web.app", "firebaseapp.com",
}


def registrable(host):
    """The registrable domain of ``host`` ("graph.facebook.com" -> "facebook.com", "bbc.co.uk" -> "bbc.co.uk")."""
    labels = host.split(".")
    if len(labels) <= 2:
        return host
    if ".".join(labels[-2:]) in MULTI_SUFFIXES:
        return ".".join(labels[-3:])
    return ".".join(labels[-2:])


def classify(host):
    """(company, category or None, matched suffix or None) for ``host``. Unknown: (registrable domain, None, None)."""
    labels = host.split(".")
    for start in range(len(labels) - 1):
        suffix = ".".join(labels[start:])
        found = DOMAINS.get(suffix)
        if found:
            return found[0], found[1], suffix
    return registrable(host), None, None
