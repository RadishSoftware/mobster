def preset(key):
    return next((dict(p) for p in PRESETS if p["key"] == key), None)


def refusal(p, apps):
    """Why Settings doesn't offer the preset ``p`` now, as a sentence that says what to do, or None when it does: it is
    gated and not tested yet, or it ``needs_app`` and Mobster's own app isn't ready (shared.Apps)."""
    if p.get("gated") and not apps.tested(p["key"]):
        return (f"Mobster hasn't finished testing {p['name']}, so it isn't offered yet. Add its server under Your own "
                "server instead")
    app = apps.get(p["key"]) if p.get("needs_app") else None
    if isinstance(app, shared.Unavailable):
        return f"{shared.why(p['name'], app.reason)}, so it isn't offered yet. Try again later"
    return None


def offered(p, apps):
    """Whether Settings offers the preset ``p`` now (``refusal``)."""
    return refusal(p, apps) is None


def not_yet(apps):
    """The presets Settings doesn't offer now, each with why, so a person looking for one (Slack) is told plainly."""
    return [{"key": p["key"], "name": p["name"], "why": refusal(p, apps) + "."}
            for p in PRESETS if not offered(p, apps)]


def public(apps):
    """The presets as GET /api/connectors gives them."""
    listed = []
    for p in (p for p in PRESETS if offered(p, apps)):
        item = {"key": p["key"], "name": p["name"], "url": p["url"], "auth": p["auth"],
                "tokenLabel": p.get("token_label"),
                "access": p["access"], "publisher": p["publisher"], "tagline": p["tagline"],
                "examples": list(p.get("examples", ())), "description": p["description"], "docs": p["docs"],
                "audience": p["audience"], "selfManaged": bool(p.get("instance_path"))}
        if p["auth"] == "mobster_app":
            app = apps.get(p["key"])
            ready = isinstance(app, oauth.MobsterApp)
            item.update({"auth": "oauth"} if ready else {"auth": p["fallback"], "fallbackReason": app.reason})
        listed.append(item)
    return listed
