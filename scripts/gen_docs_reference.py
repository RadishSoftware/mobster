STATES_START, STATES_END = "{/* states:start */}", "{/* states:end */}"


def state_groups():
    """[(heading, [row])]: the rows a person can act on, grouped by what they are about. A row that clears by itself
    (its fix is ``Wait``) has nothing to answer."""
    from mobile_agent import states
    groups = (("Your iPhone needs you", (states.WAITING_FOR_PHONE,)),
              ("Mobster's helper and setup", (states.HELPER_DOWN, states.NO_PHONE)),
              ("Your AI account and network", (states.MODEL_UNAVAILABLE,)),
              ("Mobster itself", (states.LIVE_OFF, states.FROZEN, states.DOWN)))
    return [(heading, [row for row in states.ROWS if row.state in kinds and not isinstance(row.fix, states.Wait)])
            for heading, kinds in groups]


def states_block():
    from mobile_agent import states
    lines = ["## When something stops", "",
             "Mobster says what stopped and what to do in the same words in Mobster for Mac, in `mobster mcp`'s "
             "`status` and in `mobster doctor`. `mobster doctor --fix` does the fix when Mobster can, and says what "
             "it did and what it couldn't.", ""]
    for heading, rows in state_groups():
        lines += [f"### {heading}", "", "<AccordionGroup>"]
        for row in rows:
            message, step, _need = states.words(row.state, row.cause)
            title = message.rstrip(".").replace('"', "&quot;")
            lines += [f'  <Accordion title="{title}">', f"    {escape(step)} {states.how(row.fix)}", "  </Accordion>"]
        lines += ["</AccordionGroup>", ""]
    return "\n".join(lines).rstrip("\n")


