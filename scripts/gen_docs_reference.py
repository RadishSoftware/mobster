KINDS = {
    "read": ("Read-only", "Reads the screen or Mobster's state and changes nothing."),
    "acts": ("Acts on the device", "Taps, types, opens or installs on a simulator or a real iPhone. A client that "
                                   "asks before destructive or open-world calls asks before these."),
    "local": ("Local", "Not read-only, and not marked destructive or open-world: it starts, judges or saves "
                       "Mobster's own runs."),
    "cancels": ("Cancels", "Stops Mobster's own run. Marked destructive, because a stop ends work, but not open-world: "
                           "it acts on Mobster, not on the device's apps."),
}


def kind_of(annotations):
    if annotations.get("readOnlyHint"):
        return "read"
    if annotations.get("openWorldHint"):
        return "acts"
    if annotations.get("destructiveHint"):
        return "acts" if annotations.get("idempotentHint") is False else "cancels"
    return "local"


FLAGS = {"--allow-files": "allow_files", "--allow-photos": "allow_photos"}  # the `mobster mcp` options that add tools


def tool_list():
    """Every tool, `verify_start`'s Smart arguments and the tracks' tools included: ToolSets built with a placeholder
    key and model, `--allow-files` and `--allow-photos` on, no device, no I/O. Each tool's ``flag`` is the option that
    lists it, or None. The instructions are the key-less server's (core and the tracks')."""
    import tempfile

    from mobile_agent import tracks
    from mobile_agent.mcp_server import tools as mcp
    tracks.load()  # the tracks' MCP tools (mcp_server/registry.py), as `mobster mcp` loads them at startup

    def names(folder, **options):
        return {tool["name"] for tool in mcp.ToolSet(runs_dir=folder, version="0", devices=lambda: [],
                                                     **options).list_tools()}
    on = {option: True for option in FLAGS.values()}
    with tempfile.TemporaryDirectory() as folder:
        keyless = mcp.ToolSet(runs_dir=folder, version="0", devices=lambda: [], **on)
        smart = mcp.ToolSet(runs_dir=folder, key="placeholder", smart_model=MODEL_SENTINEL, version="0",
                            devices=lambda: [], **on)
        listed = {tool["name"]: tool for tool in smart.list_tools()}
        instructions = keyless.instructions()
        plain = names(folder)
        flag_of = {name: flag for flag, option in FLAGS.items() for name in names(folder, **{option: True}) - plain}
    for name, tool in listed.items():
        # The model's name is the placeholder in the description and in an argument's: say what it stands for.
        listed[name] = tool = json.loads(re.sub(re.escape(MODEL_SENTINEL) + r", on the user's \w+ key",
                                                "`<model>`, on the user's `<provider>` key", json.dumps(tool)))
        tool["flag"] = flag_of.get(name)
    return list(listed.values()), instructions


def type_of(schema):
    """A short, plain type for a property schema, such as "string, length 1–128" or "up | down | left | right"."""
    kind = schema.get("type")
    if "enum" in schema:
        text = " | ".join(json.dumps(v) for v in schema["enum"])
    elif kind == "array":
        text = "array of " + (type_of(schema.get("items", {})) if schema.get("items") else "any")
    elif kind == "object" and "properties" in schema:
        text = "object: " + ", ".join(schema["properties"])
    else:
        text = kind or "any"
    bounds = []
    for low, high, word in (("minimum", "maximum", ""), ("exclusiveMinimum", "maximum", "above "),
                            ("minLength", "maxLength", "length "), ("minItems", "maxItems", "items ")):
        if low in schema and high in schema and schema.get(high) is not None:
            bounds.append(f"{word}{schema[low]:,}–{schema[high]:,}" if not word.startswith("above")
                          else f"more than {schema[low]:,}, at most {schema[high]:,}")
        elif low in schema:
            bounds.append(f"{word}at least {schema[low]:,}" if not word.startswith("above")
                          else f"more than {schema[low]:,}")
        elif high in schema and low == "minimum":
            bounds.append(f"at most {schema[high]:,}")
        elif high in schema and low in ("minLength", "minItems"):
            bounds.append(f"{word}at most {schema[high]:,}")
    if "exclusiveMaximum" in schema:
        bounds.append(f"less than {schema['exclusiveMaximum']:,}")
    if "pattern" in schema:
        bounds.append("matching " + schema["pattern"])
    return text + (f" ({', '.join(bounds)})" if bounds else "")


def tool_section(tool):
    name, schema, annotations = tool["name"], tool["inputSchema"], tool["annotations"]
    kind, why = KINDS[kind_of(annotations)]
    hints = ", ".join(f"`{key}: {json.dumps(value)}`" for key, value in annotations.items())
    lines = [f"## {code(name)}", "", escape(tool["description"]), "",
             f"**{kind}.** {why}"
             + (f" Listed only when the server is started with `{tool['flag']}`." if tool["flag"] else ""), "",
             f"Annotations: {hints}", ""]
    properties, required = schema.get("properties", {}), set(schema.get("required", []))
    if properties:
        lines += ["**Arguments**", ""]
        for prop_name, spec in properties.items():
            default = json.dumps(spec["default"]) if "default" in spec else None
            lines += field(prop_name, type_of(spec), escape(spec.get("description", "")), default=default,
                           required=prop_name in required)
    else:
        lines += ["Takes no arguments.", ""]
    lines += [f'<Accordion title="Input schema of {name}">', "", "```json",
              json.dumps(schema, indent=2, ensure_ascii=False), "```", "", "</Accordion>", ""]
    return lines


