# The Optional section: mobster.dev's pages for the people the docs don't cover (llmstxt.org's "Optional").
ELSEWHERE = [
    ("Mobster for Mac", "https://mobster.dev", "Download the Mac app, see pricing and buy a license."),
    ("Integrations", "https://mobster.dev/integrations",
     "Setting Mobster up in Claude Code, Codex, Cursor, Claude Desktop, VS Code, Gemini CLI and other agents."),
    ("Compare", "https://mobster.dev/compare", "Mobster beside TapKit, Maestro, Appium and XCUITest."),
    ("Blog", "https://mobster.dev/blog", "Guides and notes from the people who make Mobster."),
    ("Mobster CLI on GitHub", "https://github.com/RadishSoftware/mobster",
     "The open-source CLI, MCP server and agent loop, under MIT."),
]


def nav_sections(node, trail=()):
    """(heading, [page]) for each group of docs.json's navigation, in order: "Tab: Group", or the tab alone."""
    if isinstance(node, list):
        for item in node:
            yield from nav_sections(item, trail)
        return
    if not isinstance(node, dict):
        return
    name = node.get("tab") or node.get("group")
    here = trail + ((name,) if name else ())
    pages = [p for p in node.get("pages", []) if isinstance(p, str)]
    if pages:
        yield ": ".join(dict.fromkeys(here)), pages
    for item in node.get("pages", []):
        if isinstance(item, dict):
            yield from nav_sections(item, here)
    for key in ("tabs", "groups"):
        if key in node:
            yield from nav_sections(node[key], here)


def page_meta(page):
    """A docs page's frontmatter title and description."""
    import yaml
    path = next(DOCS / f"{page}{suffix}" for suffix in (".mdx", ".md") if (DOCS / f"{page}{suffix}").is_file())
    match = re.match(r"---\n(.*?)\n---\n", path.read_text(), re.S)
    meta = yaml.safe_load(match[1]) if match else {}
    return meta.get("title") or page, " ".join(str(meta.get("description") or "").split())


def llms_txt():
    site = json.loads((DOCS / "docs.json").read_text())
    lines = [f"# {site['name']}", "", f"> {site['description']}", "",
             "Mobster for Mac is the app: guided setup for each iPhone, a live view, conversations with approvals, "
             "memory, files, voice, history and schedules. Mobster CLI is its free, open-source engine: the "
             "`mobster` command, its MCP server and the agent loop. Every page below is Markdown at its link. The "
             f"whole site in one file is {SITE_URL}/llms-full.txt.", ""]
    for heading, pages in nav_sections(site["navigation"]):
        lines += [f"## {heading}", ""]
        for page in pages:
            title, description = page_meta(page)
            lines.append(f"- [{title}]({SITE_URL}/{page}.md)" + (f": {description}" if description else ""))
        lines.append("")
    lines += ["## Optional", ""]
    lines += [f"- [{title}]({url}): {description}" for title, url, description in ELSEWHERE]
    return "\n".join(lines) + "\n"


PAGES = {REFERENCE / "cli.mdx": cli_page, REFERENCE / "mcp-tools.mdx": mcp_page, DOCS / "llms.txt": llms_txt}


def stale():
    """The pages whose committed text differs from what the code generates now: [(path, expected)]."""
    out = []
    for path, render in PAGES.items():
        text = render()
        if not path.is_file() or path.read_text() != text:
            out.append((path, text))
    return out


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a page is stale instead of writing it")
    args = parser.parse_args(argv)
    changed = stale()
    if args.check:
        for path, _ in changed:
            print(f"{path.relative_to(ROOT)} is stale: run `{COMMAND}`", file=sys.stderr)
        return 1 if changed else 0
    REFERENCE.mkdir(parents=True, exist_ok=True)
    for path, text in changed:
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    if not changed:
        print("docs/reference and docs/llms.txt are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
