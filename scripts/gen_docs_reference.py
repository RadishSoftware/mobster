CODE_TOKEN = re.compile(r"(?<![\w`$-])(--[a-z][a-z0-9-]*(?:=[^\s,;)]+)?|\$[A-Z][A-Z0-9_]+)")


def escape(text, table=False):
    """Help text as MDX. Options and $VARIABLES become code, so `--app` isn't typeset as an em dash; outside code,
    braces and angle brackets are literal (MDX would read them as an expression or a tag); in a table cell, pipes
    are escaped everywhere."""
    parts = re.split(r"(`[^`]*`)", text)
    parts = [part if part.startswith("`") else CODE_TOKEN.sub(r"`\1`", part) for part in parts]
    out = []
    for part in re.split(r"(`[^`]*`)", "".join(parts)):
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            out.append(part.replace("|", "\\|") if table else part)
            continue
        part = re.sub(r"([\\{}<>*\[\]])", r"\\\1", part)
        out.append(part.replace("|", "\\|") if table else part)
    # A line that starts with "import" or "export" is an ESM statement to MDX, and the page fails to compile.
    return re.sub(r"^(import|export)\b", lambda m: f"&#{ord(m.group(1)[0])};{m.group(1)[1:]}", "".join(out))


def prop(value):
    """A JSX attribute value: a JSON string inside braces, so any quote or brace in it stays literal."""
    return "{" + json.dumps(value, ensure_ascii=False) + "}"


def field(name, type_, body, default=None, required=False, post=()):
    """A Mintlify ResponseField: one argument with its type, default and description."""
    attributes = [f"name={prop(name)}", f"type={prop(type_)}"]
    if default:
        attributes.append(f"default={prop(default)}")
    if required:
        attributes.append("required")
    if post:
        attributes.append(f"post={prop(list(post))}")
    if not body.strip():
        return [f"<ResponseField {' '.join(attributes)} />", ""]
    return [f"<ResponseField {' '.join(attributes)}>", body.strip(), "</ResponseField>", ""]


def paragraphs(text):
    """A help description wrapped for a terminal, as paragraphs: blank lines split them, line breaks join."""
    blocks = re.split(r"\n\s*\n", (text or "").strip())
    return [" ".join(line.strip() for line in block.splitlines()) for block in blocks if block.strip()]


def code(text):
    return "`" + text.replace("`", "'") + "`"


def og_card(tab, alt):
    """The docs tab's share card, drawn by mobster.dev (site/app/og/docs/[card]/route.tsx), as page meta tags."""
    url = f"https://mobster.dev/og/docs/{tab}.jpg"
    return {"og:image": url, "og:image:alt": alt, "twitter:image": url}


def frontmatter(title, sidebar, description, icon, meta=None):
    """`icon` is the sidebar's Lucide icon; `meta` adds page meta tags (Mintlify's quoted keys, such as "og:image")."""
    tags = [f"{json.dumps(key)}: {json.dumps(value)}" for key, value in (meta or {}).items()]
    return "\n".join(["---", f"title: {json.dumps(title)}", f"sidebarTitle: {json.dumps(sidebar)}",
                      f"description: {json.dumps(description)}", f"icon: {json.dumps(icon)}", *tags, "---", ""])


def build_parser():
    """`mobster`'s parser with extensions off: the public tree's commands only."""
    from mobile_agent import cli_parser as cli
    from mobile_agent import harness_api
    with mock.patch.object(harness_api.hooks(), "cli", []):
        return cli.build_parser(), cli.EVERYDAY


def subparsers(parser):
    return next((a for a in parser._actions if isinstance(a, argparse._SubParsersAction)), None)


def commands_of(parser, order=()):
    """[(name, help, subparser)] in `--help` order: ``order`` first, then the rest as added; aliases once."""
    subs = subparsers(parser)
    if subs is None:
        return []
    helps = {action.dest: action.help for action in subs._choices_actions}
    seen, listed = set(), []
    for name, sub in subs.choices.items():
        if id(sub) in seen:
            continue
        seen.add(id(sub))
        listed.append((name, helps.get(name) or "", sub))
    rank = {name: i for i, name in enumerate(order)}
    return sorted(listed, key=lambda item: (rank.get(item[0], len(rank)), listed.index(item)))


def takes(action):
    """What an argument takes, in plain words for a field's type."""
    if action.nargs == 0:
        return "flag"
    if action.choices and not isinstance(action, argparse._SubParsersAction):
        value = " | ".join(str(choice) for choice in action.choices)
    else:
        value = action.metavar if isinstance(action.metavar, str) else (action.dest or "").upper()
    more = {"?": "optional", "*": "zero or more", "+": "one or more", argparse.REMAINDER: "the rest"}.get(action.nargs)
    return f"{value}, {more}" if more else value


def repeatable(action):
    return isinstance(action, argparse._AppendAction) or type(action).__name__.endswith("Expectation")


def stated_default(help_text):
    """The default an option's help states, "(default: 30)" or "; default: $MOBSTER_ENV_FILE", or None."""
    match = (re.search(r"\(default:? ([^)]*)\)", help_text or "")
             or re.search(r"(?:^|; )default:? ([^;]+)$", help_text or ""))
    return match[1].strip() if match else None


def default_of(action):
    """The parser's default, else the one its help states (the command decides it at run time), else None."""
    if isinstance(action, argparse._VersionAction):
        return None
    if action.default in (None, argparse.SUPPRESS) or action.nargs == 0 and action.default is False:
        return stated_default(action.help) or ("off" if action.nargs == 0 else None)
    if action.const is not None and action.nargs == "?":
        return f"{action.default}; {action.const} when given with no value"
    if isinstance(action.default, (list, tuple)):
        return ", ".join(map(str, action.default)) or None
    return str(action.default)


def visible(parser):
    return [a for a in parser._actions if a.help is not argparse.SUPPRESS
            and not isinstance(a, (argparse._HelpAction, argparse._SubParsersAction))]


def argument_fields(parser):
    lines = []
    actions = visible(parser)
    positionals = [a for a in actions if not a.option_strings]
    options = [a for a in actions if a.option_strings]
    if positionals:
        lines += ["**Arguments**", ""]
        for action in positionals:
            metavar = action.metavar if isinstance(action.metavar, str) else action.dest.upper()
            required = action.nargs not in ("?", "*", argparse.REMAINDER)
            lines += field(metavar, takes(action), escape(action.help or ""), required=required)
    if options:
        lines += ["**Options**", ""]
        for action in options:
            lines += field(", ".join(action.option_strings), takes(action), escape(action.help or ""),
                           default=default_of(action), required=action.required,
                           post=["repeatable"] if repeatable(action) else ())
    for group in parser._mutually_exclusive_groups:
        names = [a.option_strings[0] if a.option_strings else (a.metavar or a.dest).upper()
                 for a in group._group_actions if a.help is not argparse.SUPPRESS]
        if len(names) > 1:
            joined = ", ".join(code(n) for n in names[:-1]) + " and " + code(names[-1])
            lines.append(f"{joined} can't be used together" + ("; one is required." if group.required else ".")
                         + "\n")
    return lines


def epilog_block(parser):
    if not parser.epilog:
        return []
    return ["```text", parser.epilog.strip("\n"), "```", ""]


def command_section(prog, help_text, parser, depth):
    # A subcommand's name is a bold line with its own anchor, not a heading, so the contents rail lists the groups and
    # their commands (the rail ran to 150 entries with every subcommand).
    if depth >= 4:
        lines = [f'<a id="{anchor(prog)}"></a>', "", f"**{code(prog)}**", ""]
    else:
        lines = [f"{'#' * depth} {code(prog)}", ""]
    described = paragraphs(parser.description) or ([help_text[:1].upper() + help_text[1:] + "."] if help_text else [])
    lines += [p for paragraph in described for p in (escape(paragraph), "")]
    if parser.get_default("stub_command"):
        # A track's command that hasn't landed: devtools.py gives it its help, and the stub only says it isn't here.
        lines += [f"This build doesn't have {code(prog)} yet: it says so and exits 3.", ""]
    lines += argument_fields(parser)
    lines += epilog_block(parser)
    children = commands_of(parser)
    if children:
        lines += ["| Command | What it does |", "|---|---|"]
        lines += [f"| [{code(f'{prog} {name}')}](#{anchor(f'{prog} {name}')}) | {escape(child_help, True)} |"
                  for name, child_help, _ in children]
        lines.append("")
        for name, child_help, child in children:
            lines += command_section(f"{prog} {name}", child_help, child, min(depth + 1, 4))
    return lines


def anchor(heading):
    """Mintlify's heading slug: lowercase, spaces to dashes, underscores kept, other punctuation dropped."""
    return re.sub(r"[^a-z0-9 _-]", "", heading.lower()).strip().replace(" ", "-")


# The contents rail groups the commands the way a person reaches for them. A command in no group lands in "More", so a
# new command shows up without a change here.
CLI_GROUPS = (
    ("Set up", ("doctor", "setup", "devices", "login", "logout", "wifi", "update", "version", "completion", "help")),
    ("Test your app", ("test", "verify", "ci", "xcode", "fixtures", "links", "env", "sim", "expo", "xray", "asc",
                       "testflight", "build-ocr")),
    ("Run tasks", ("chat", "run", "tui", "demo", "history", "export", "memory", "workflow", "screen", "phone",
                   "alerts")),
    ("Connect agents and tools", ("mcp", "serve", "api", "audit")),
)


def cli_groups(commands):
    """[(group, [command])]: CLI_GROUPS' order, each group's commands in its own order, the rest under "More"."""
    by_name = {command[0]: command for command in commands}
    groups = [(title, [by_name.pop(n) for n in names if n in by_name]) for title, names in CLI_GROUPS]
    return [(title, found) for title, found in [*groups, ("More", list(by_name.values()))] if found]


