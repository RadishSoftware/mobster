def app_api_page():
    from mobile_agent.app_api import endpoints
    from mobile_agent.packs.register import all_packs
    found = endpoints.endpoints(all_packs())
    lines = [frontmatter("App API reference", "App API endpoints",
                         "Every App API endpoint, as a REST route and as an MCP tool, with its parameters and answer, "
                         "generated from the OpenAPI description the App API serves.", "table"),
             NOTICE.replace("SOURCE", "the App API's endpoints (mobile_agent/app_api/endpoints.py) and the app packs"),
             "",
             "Each endpoint below is `GET /v1/<app>/<thing>` on the App API and the MCP tool `<app>_<thing>` in "
             "Mobster's MCP server, with the same parameters and the same answer. `GET /v1/screen` (`read_screen`) "
             "reads the screen in front, in any app, into the fields you name. Every endpoint only reads: it may tap, "
             "type and scroll to reach the screen and read it, and never likes, follows, comments, sends, posts, "
             "buys or deletes. "
             "[App API](/app-api) shows how to call it, and "
             "[MCP server](/mcp-server#app-tools) how an agent does.",
             "",
             "| Endpoint | MCP tool | What it reads |", "|---|---|---|"]
    for endpoint in found:
        lines.append(f"| [{code('GET ' + endpoint.path)}](#{anchor(endpoint.name)}) | {code(endpoint.name)} | "
                     f"{escape(endpoint.title, True)} in {escape(endpoint.app_name, True)} |")
    lines.append("")
    for endpoint in found:
        lines += [f"## {code(endpoint.name)}", "", f"`GET {endpoint.path}`", "", escape(endpoint.description), "",
                  "**Parameters** (query string, or the MCP tool's arguments)", ""]
        for name, spec in endpoint.input_schema["properties"].items():
            default = json.dumps(spec["default"]) if "default" in spec else None
            lines += field(name, type_of(spec), escape(spec.get("description", "")), default=default)
        lines += ["**Answer**", ""]
        for name, spec in endpoint.output_schema["properties"].items():
            kinds = spec.get("type")
            lines += field(name, " or ".join(kinds) if isinstance(kinds, list) else kinds or "any",
                           escape(spec.get("description", "")))
    # The whole OpenAPI document, inlined, is 18,000 lines: Mintlify's compiler overflows its stack on a code block
    # that long and the page shows a parsing error. The running App API serves the same document.
    lines += ["## The OpenAPI description", "",
              "`GET /v1/openapi.json` on the running App API returns the OpenAPI 3.1 description of every endpoint "
              "above. [App API](/app-api) shows how to start it.", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


