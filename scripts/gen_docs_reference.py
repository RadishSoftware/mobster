#!/usr/bin/env python3
"""Generate the docs site's reference pages from the code, so they can't drift from it.

- docs/reference/cli.mdx: every `mobster` command, subcommand, argument and option, with its default, read from
  the argparse parsers (`mobile_agent.cli_parser.build_parser`).
- docs/reference/mcp-tools.mdx: every tool `mobster mcp` offers, with its description, input schema and MCP
  annotations (read-only or acting), read from `mobile_agent.mcp_server.tools.ToolSet` with the tracks' tools
  loaded (`mobile_agent.tracks.load`, which does no I/O) and `--allow-files` and `--allow-photos` on, so the tools
  those options add are listed too, each marked with its option.
- docs/reference/app-api.mdx: every App API endpoint (REST `GET /v1/<app>/<thing>` and its MCP tool `<app>_<thing>`),
  with its parameters and answer, from the OpenAPI description the App API serves (`mobile_agent.app_api.openapi`),
  built from the app packs this build has.
- docs/reference/parity.mdx: every capability against the command line, the local API and MCP, from
  `mobile_agent.parity` checked against the parsers, the routes and the tool list: where each is offered, why it isn't
  where it was left out on purpose, and the open gaps ranked.
- docs/faq.mdx: its "When something stops" section, between the `states:start` and `states:end` comments, one answer
  for each row of the table of states (`mobile_agent/states.py`), in the words the Mac app, `mobster mcp` and
  `mobster doctor` use. The rest of the page is written by hand.
- docs/llms.txt: the site's index for AI tools (llmstxt.org), served at docs.mobster.dev/llms.txt. Every page in
  docs/docs.json's navigation, in its order, with its frontmatter title and description and a link to its Markdown.
  On 8 Oct 2026 Mintlify served llms-full.txt but answered 404 for its own generated llms.txt (the deployment is set
  to noindex). A committed llms.txt at the docs root replaces the generated one, so the site always has this copy.

Nothing starts: the parsers are built with extensions off (the public tree's commands only, as
mobile_agent/tests/test_docs.py does), and the tool list comes from a ToolSet that never discovers a device or
opens a server. The output depends only on the code: no version, date, path or environment value reaches it.

    python scripts/gen_docs_reference.py           write the pages
    python scripts/gen_docs_reference.py --check   exit 1 if a committed page differs from the code

mobile_agent/tests/test_docs_site.py fails when a committed page is stale.
"""

