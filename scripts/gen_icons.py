"""Write every surface's copy of Mobster's icons from their one source, docs/brand/icons/.

    python3 scripts/gen_icons.py           write them
    python3 scripts/gen_icons.py --check   write nothing; exit 1 if a copy differs from its source

The source is one SVG per icon on a 24 unit grid (docs/brand/icons/svg/<name>.svg; <name>.16.svg, where there is one,
is the drawing for 16 px and under) and icons.json, which names each
icon's motion and which surfaces outside the Mac app carry it. An element a motion moves sits in a <g data-part> group
(data-origin is the point it turns or scales about, on the grid). An icon with a motion and no part moves whole: it is
moved as a box (icon.css moves the <svg> itself, which costs no SVG layout). A `draw` part's lines get pathLength="1",
so the line draws in on any length; a drawing that is all one check is wrapped in one `draw` group here.

The copies:
  dashboard/src/components/ui/icons.gen.ts   every icon, for <Icon> (components/ui/icon.tsx)
  site/components/ui/icon*.{tsx,css}, icons.gen.ts   copied by scripts/gen_brand_tokens.py (scripts/ui-manifest.json)
  relay/src/pages/icons.gen.ts               Remote's icons as SVG strings, for its server-rendered pages

The docs (Mintlify) name Lucide's icons, the same drawings, which Mintlify draws itself in the text colour: it shows an
icon file of ours as an image, which can't take the colour (tried 17 Oct 2026), so none is generated for them.

Standard library only.
"""

import json
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "brand" / "icons"
DASHBOARD = ROOT / "dashboard" / "src" / "components" / "ui"
RELAY = ROOT / "relay" / "src" / "pages" / "icons.gen.ts"
NS = "{http://www.w3.org/2000/svg}"
TAGS = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse", "g"}
# What a drawn element may say. Paint is the icon's (currentColor, the stroke from icon.css); an element only says
# where it is, and the few that are filled or faint say so.
SHAPE = {"d", "cx", "cy", "r", "rx", "ry", "x", "y", "x1", "x2", "y1", "y2", "width", "height", "points"}
PAINT = {"fill", "fill-opacity", "fill-rule", "opacity"}
PART = re.compile(r"^[a-z]+(?:-[a-z0-9]+)*$")
# The parts each motion must have (icon.css). A motion not listed moves its named part when the drawing has one (an
# arrow, a pen, an x), else the whole icon.
NEEDS = {
    "lid": {"lid"}, "shackle": {"shackle"}, "spread": {"out-a", "out-b"}, "stack": {"front"}, "lift": {"top"},
    "ring": {"body"}, "tick": {"hand"}, "sweep": {"hand"}, "draw": {"draw"}, "bounce": {"dot-1", "dot-2", "dot-3"},
    "bars": {"bar-1", "bar-2", "bar-3"}, "waves": {"wave-1", "wave-2", "wave-3"}, "clap": {"board"},
    "focus": {"frame"}, "grid": {"tile-1", "tile-2", "tile-3", "tile-4"}, "snap": {"out-a", "out-b"},
    "spin-meridian": {"meridian"}, "cursor": {"cursor"},
}
GENERATED = "Generated by scripts/gen_icons.py from docs/brand/icons. Don't edit: change the source and run it."


def camel(name):
    return re.sub(r"-([a-z])", lambda m: m.group(1).upper(), name)


def number(value):
    return ("%.3f" % float(value)).rstrip("0").rstrip(".")


def read(path):
    """An icon's drawing as nodes: (tag, attrs, children). Fails on anything outside the drawing vocabulary."""
    root = ET.parse(path).getroot()
    if root.tag != NS + "svg" or root.get("viewBox") != "0 0 24 24":
        raise SystemExit(f"{path.name}: the root must be <svg viewBox=\"0 0 24 24\">")
    fill = root.get("data-fill") is not None

    def node(element):
        tag = element.tag.removeprefix(NS)
        if tag not in TAGS:
            raise SystemExit(f"{path.name}: <{tag}> isn't part of the drawing vocabulary ({', '.join(sorted(TAGS))})")
        attrs = {}
        for key, value in element.attrib.items():
            if key in SHAPE | PAINT:
                if (key in PAINT and key != "fill-rule" and value not in ("currentColor", "none")
                        and not re.fullmatch(r"\.?\d*\.?\d+", value)):
                    raise SystemExit(f"{path.name}: {key}=\"{value}\": paint is currentColor or an opacity")
                attrs[key] = value
            elif key == "data-part" and tag == "g" and PART.match(value):
                attrs[key] = value
            elif key == "data-origin" and tag == "g":
                x, y = value.split()
                attrs[key] = f"{number(x)} {number(y)}"
            else:
                raise SystemExit(f"{path.name}: <{tag} {key}> isn't allowed; an icon says where its lines are, nothing "
                                 "else")
        children = [node(child) for child in element]
        if tag != "g" and children:
            raise SystemExit(f"{path.name}: only a <g> holds other elements")
        return (tag, attrs, children)

    return fill, [node(child) for child in root]


def parts(nodes):
    found = set()
    for tag, attrs, children in nodes:
        if "data-part" in attrs:
            found.add(attrs["data-part"])
        found |= parts(children)
    return found


def prepare(name, spec, nodes, motions):
    """Wrap a moving icon with no parts in one group, and mark draw parts' lines so they draw on any length."""
    motion = spec.get("motion")
    if motion is None:
        if parts(nodes):
            raise SystemExit(f"{name}: has parts but no motion in icons.json")
        return nodes
    if motion not in motions:
        raise SystemExit(f"{name}: motion {motion!r} isn't one of icons.json's motions")
    have = parts(nodes)
    if not have and motion == "draw":
        nodes = [("g", {"data-part": "draw"}, nodes)]
        have = parts(nodes)
    need = NEEDS.get(motion)
    if need and not need & have:
        raise SystemExit(f"{name}: motion {motion!r} moves {', '.join(sorted(need))}; the drawing has "
                         f"{', '.join(sorted(have))}")

    def mark(node, drawing=False):
        tag, attrs, children = node
        drawing = drawing or attrs.get("data-part") == "draw"
        attrs = dict(attrs)
        if drawing and tag != "g":
            attrs["pathLength"] = "1"
        return (tag, attrs, [mark(child, drawing) for child in children])

    return [mark(node) for node in nodes]


def load():
    manifest = json.loads((SOURCE / "icons.json").read_text())
    files = {path.stem: path for path in sorted((SOURCE / "svg").glob("*.svg")) if "." not in path.stem}
    small = {path.stem.split(".")[0]: path for path in sorted((SOURCE / "svg").glob("*.16.svg"))}
    if set(small) - set(files):
        raise SystemExit(f"a 16 px drawing with no icon: {sorted(set(small) - set(files))}")
    names = set(manifest["icons"])
    if set(files) != names:
        missing, extra = sorted(names - set(files)), sorted(set(files) - names)
        raise SystemExit(f"icons.json and svg/ differ: no drawing for {missing}; not in icons.json: {extra}")
    motions = manifest["motions"]
    icons = {}
    for name in sorted(names):
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
            raise SystemExit(f"{name}: icon names are lowercase kebab-case")
        fill, nodes = read(files[name])
        spec = manifest["icons"][name]
        prepared = prepare(name, spec, nodes, motions)
        icons[name] = {"fill": fill, "motion": spec.get("motion"), "nodes": prepared,
                       "whole": bool(spec.get("motion")) and not parts(prepared)}
        if name in small:
            small_fill, small_nodes = read(small[name])
            if small_fill != fill:
                raise SystemExit(f"{name}.16.svg: filled where {name}.svg isn't, or the other way round")
            icons[name]["small"] = prepare(name, spec, small_nodes, motions)
    for surface, listed in manifest["surfaces"].items():
        unknown = sorted(set(listed) - names)
        if unknown:
            raise SystemExit(f"surfaces.{surface} names icons with no drawing: {unknown}")
    return manifest, icons


def ts_node(node, depth):
    tag, attrs, children = node
    pairs = []
    for key, value in attrs.items():
        if key == "data-origin":
            x, y = value.split()
            pairs.append(f"origin: '{x}px {y}px'")
        else:
            prop = key if key.startswith("data-") else camel(key)
            pairs.append(f"{prop if re.fullmatch(r'[A-Za-z]+', prop) else repr(prop)}: '{value}'")
    text = f"['{tag}', {{ {', '.join(pairs)} }}"
    if children:
        inner = ", ".join(ts_node(child, depth + 1) for child in children)
        text += f", [{inner}]"
    return text + "]"


def render_ts(manifest, icons, names, header):
    motions = manifest["motions"]
    stroke = manifest["stroke"]
    lines = [
        f"// {GENERATED}",
        *(f"// {line}" for line in header),
        "",
        "/** One drawn element: its tag, its attributes (React's names; `origin` is where a part turns, "
        "on the grid) and",
        " *  a group's children. */",
        "export type IconNode = readonly [tag: string, attrs: Readonly<Record<string, string>>, "
        "children?: readonly IconNode[]]",
        "/** How an icon moves (icon.css). A hold motion plays while its control is hovered, a once motion plays to "
        "the end, a loop turns until the icon goes. */",
        "export type IconMotion = " + " | ".join(f"'{m}'" for m in motions),
        "/** `small` is the drawing for 16 px and under, where the full one's details would close up. `whole`: the "
        "motion moves",
        " *  the whole icon (the <svg> as a box), not a part of it. */",
        "export type IconDef = { readonly nodes: readonly IconNode[]; readonly small?: readonly IconNode[]; readonly "
        "motion?: IconMotion; readonly whole?: true; readonly fill?: true }",
        "",
        "export const MOTION_KIND: Readonly<Record<IconMotion, 'hold' | 'once' | 'loop'>> = {",
        *(f"  {repr(m) if '-' in m else m}: '{kind}'," for m, kind in motions.items()),
        "}",
        "",
        f"/** The sizes an icon is drawn at, in CSS px. Its line is {stroke['base']} + size × {stroke['perPx']} px "
        "(icons.json › stroke). */",
        "export const ICON_SIZES = [" + ", ".join(str(s) for s in manifest["sizes"]) + "] as const",
        "",
        "const DATA = {",
    ]
    for name in names:
        icon = icons[name]
        fields = []
        if icon["motion"]:
            fields.append(f"motion: '{icon['motion']}'")
        if icon["whole"]:
            fields.append("whole: true")
        if icon["fill"]:
            fields.append("fill: true")
        fields.append("nodes: [" + ", ".join(ts_node(node, 2) for node in icon["nodes"]) + "]")
        if icon.get("small"):
            fields.append("small: [" + ", ".join(ts_node(node, 2) for node in icon["small"]) + "]")
        key = f"'{name}'" if "-" in name else name
        lines.append(f"  {key}: {{ {', '.join(fields)} }},")
    lines += ["} satisfies Record<string, IconDef>", "", "export type IconName = keyof typeof DATA",
              "export const ICONS: Readonly<Record<IconName, IconDef>> = DATA", ""]
    return "\n".join(lines)


def svg_text(node):
    tag, attrs, children = node
    rendered = []
    for key, value in attrs.items():
        if key == "data-origin":
            x, y = value.split()
            rendered.append(f'style="transform-box:view-box;transform-origin:{x}px {y}px"')
        else:
            rendered.append(f'{key}="{value}"')
    open_tag = f"<{tag}{''.join(' ' + a for a in rendered)}"
    if children:
        return open_tag + ">" + "".join(svg_text(child) for child in children) + f"</{tag}>"
    return open_tag + "/>"


def render_relay(manifest, icons):
    names = sorted(manifest["surfaces"]["remote"])
    lines = [
        f"// {GENERATED}",
        "// Remote's icons, drawn by the same source as the Mac app's <Icon>. icon() returns the <svg> for a page, "
        "painted by",
        "// its own attributes (the pages' CSP allows no inline style, and their stylesheet has no room): "
        "currentColor, and",
        "// the app's line, 0.5 + size / 16 px, as grid units.",
        "",
        "export const ICON_BODY = {",
        *(f"  {json.dumps(name)}: {json.dumps(''.join(svg_text(n) for n in icons[name]['nodes']))}," for name in names),
        "} as const;",
        "const FILLED: ReadonlySet<string> = new Set(" + json.dumps([n for n in names if icons[n]["fill"]]) + ");",
        "",
        "export type IconName = keyof typeof ICON_BODY;",
        "",
        "/** An icon beside words (aria-hidden), at 12 to 24 px, with any classes the page styles it by. */",
        "export function icon(name: IconName, size: 12 | 14 | 16 | 20 | 24 = 16, className = \"\"): string {",
        "  const paint = FILLED.has(name) ? 'fill=\"currentColor\"'",
        "    : `fill=\"none\" stroke=\"currentColor\" stroke-width=\"${+(12 / size + 1.5).toFixed(3)}\" "
        "stroke-linecap=\"round\" stroke-linejoin=\"round\"`;",
        "  const classes = className ? ` class=\"${className}\"` : \"\";",
        "  return `<svg${classes} data-icon=\"${name}\" viewBox=\"0 0 24 24\" width=\"${size}\" height=\"${size}\" "
        "${paint} aria-hidden=\"true\" focusable=\"false\">${ICON_BODY[name]}</svg>`;",
        "}",
        "",
    ]
    return "\n".join(lines)



def outputs():
    manifest, icons = load()
    out = {}
    out[DASHBOARD / "icons.gen.ts"] = render_ts(manifest, icons, sorted(icons), [
        "Every icon the Mac app draws, by name. Draw one with <Icon name> (icon.tsx); the motions are in icon.css."])
    if manifest["surfaces"]["remote"]:
        out[RELAY] = render_relay(manifest, icons)
    return out


def main(argv):
    out = outputs()
    if "--check" in argv:
        stale = [path for path, text in out.items() if not path.exists() or path.read_text() != text]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale: run python3 scripts/gen_icons.py", file=sys.stderr)
        return 1 if stale else 0
    for path, text in out.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
