SCANNED = {".mdx", ".css", ".ts", ".tsx", ".mjs", ".js", ".html"}


def scanned_text(options, text, path):
    """The file outside its regions, and the files the region's ``scan=a,b`` names (folders or files, from the root)."""
    found = REGION.sub("", text)
    for name in filter(None, options.get("scan", "").split(",")):
        root = ROOT / name
        for file in [root] if root.is_file() else sorted(root.rglob("*")):
            if file.is_file() and file.suffix in SCANNED and file != path:
                found += "\n" + REGION.sub("", file.read_text(errors="replace"))
    return found


def used_names(options, text, path):
    """The token names the surface reads: every var(--[prefix]name) in the text ``scanned_text`` gathers."""
    prefix = re.escape(options.get("prefix", ""))
    return set(re.findall(r"var\(--" + prefix + r"([\w-]+)", scanned_text(options, text, path)))


def region(match, tokens, text="", path=None):
    options = dict(option.split("=", 1) for option in match.group("options").split())
    begin = match.group(0)[:match.group(0).index("*/") + 2]
    if options.get("as") == "mintlify":
        return f"{begin}\n{docs_faces(tokens)}{mintlify_greys(tokens)}\n{END}"
    if options.get("as") == "email":
        return f"{begin}\n{email_tokens(tokens)}\n{END}"
    if options.get("as") == "ui":
        pad = " " * int(options.get("indent", 2))
        return begin + "\n" + "\n".join(pad + line
                                        for line in ui_vars(tokens, options["scheme"])) + f"\n{pad[:-2]}{END}"
    # A surface that says what to scan gets only the tokens it reads; without a path (a test's snippet), all of them.
    used = used_names(options, text, path) if path else None
    if path and (stale := unknown(tokens, used, scanned_text(options, text, path), options.get("prefix", ""))):
        names = ", ".join("--" + options.get("prefix", "") + name for name in stale)
        raise SystemExit(f"{path.relative_to(ROOT)}: reads {names}, which docs/brand/tokens.json doesn't have; "
                         "use the token's current name")
    keep = needed(tokens, used) if path else None
    css = stylesheet(tokens, keep=keep)
    if options.get("dark"):
        css = css.replace("@media (prefers-color-scheme: dark) {\n  :root {", options["dark"] + " {", 1)
        css = css[:css.rindex("}")].rstrip() + "\n"  # the media query's own closing brace
        css = css.replace("  color-scheme: light dark;\n", "")  # the page sets its own
    return f"{begin}\n{compact(prefixed(css, options.get('prefix', '')))}\n{END}"


def regions(text, tokens, path=None):
    return REGION.sub(lambda match: region(match, tokens, text, path), text)


