def pixel_mark(colour, ground):
    """The 16 px mark in whole pixels, for the terminal's half blocks: each slab, then each round corner's pixel at
    60% over the ground. [(x, y, width, height, "#RRGGBB")], drawn in order."""
    soft = _mix(colour, 0.6, ground)
    rects = []
    for x, y, w, h, _r, _s, corners in MARK[16]:
        rects.append((x, y, w, h, colour.upper()))
        pixels = ((x + w - 1, y), (x + w - 1, y + h - 1), (x, y + h - 1), (x, y))
        rects += [(px, py, 1, 1, soft) for (px, py), rounded in zip(pixels, corners) if rounded]
    return rects


def _compact(d, digits=1):
    """Path data at a tenth of a unit (a hundredth on the 16 and 32 px grids), relative, with no separator a parser
    doesn't need: the site inlines it on every page. A tenth of the 512 grid is 0.004 px of a 16 px mark. Each point
    is rounded before its offset is taken, so the rounding never adds up along the path."""
    def number(value):
        text = f"{value:.{digits}f}".rstrip("0").rstrip(".")
        text = "0" if text in ("-0", "") else text
        return text.replace("0.", ".", 1) if text.lstrip("-").startswith("0.") else text

    def join(values):
        return re.sub(r" (?=-)", "", " ".join(number(v) for v in values))

    out, x, y, start = [], 0.0, 0.0, (0.0, 0.0)
    for command, numbers in re.findall(r"([MLHVCQAZ])([^MLHVCQAZ]*)", d):
        values = [round(float(n), digits) for n in re.findall(r"-?\d+(?:\.\d+)?(?:e-?\d+)?", numbers)]
        if command == "Z":
            out.append("z")
            x, y = start
        elif command == "H":
            out.append("h" + join([values[0] - x]))
            x = values[0]
        elif command == "V":
            out.append("v" + join([values[0] - y]))
            y = values[0]
        elif command == "A":
            rx, ry, rotation, large, sweep, ex, ey = values
            out.append("a" + join([rx, ry, rotation, large, sweep, ex - x, ey - y]))
            x, y = ex, ey
        else:
            pairs = [(values[i], values[i + 1]) for i in range(0, len(values), 2)]
            size = {"C": 3, "Q": 2}.get(command, 1)
            offsets = []
            for i in range(0, len(pairs), size):
                offsets += [c for px, py in pairs[i:i + size] for c in (px - x, py - y)]
                x, y = pairs[i + size - 1]
            if command == "M":
                start = pairs[0]
            first = command == "M" and not out
            out.append("M" + join(pairs[0]) if first else command.lower() + join(offsets))
    return "".join(out)


