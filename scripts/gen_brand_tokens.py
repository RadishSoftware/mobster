P_SECTION = re.compile(r"^  /\* ─── (?P<name>.*?) ─+ \*/\n", re.M)


def _sections(css, titles):
    heads = list(P_SECTION.finditer(css)) or list(re.finditer(r"^/\* ─── (?P<name>.*?) ─+ \*/\n", css, re.M))
    out = []
    for i, head in enumerate(heads):
        if head["name"].startswith(titles):
            out.append(css[head.end():heads[i + 1].start() if i + 1 < len(heads) else len(css)])
    return out


def primitive_sections(css):
    """The named sections of ui.css, in the file's order, without the @layer they sit in;
    then the LogoTile's, from art.css."""
    out = _sections(css[:css.rindex("}")], PRIMITIVE_SECTIONS)
    if len(out) != len(PRIMITIVE_SECTIONS):
        raise ValueError(f"{PRIMITIVES_CSS.name}: expected the sections {PRIMITIVE_SECTIONS}, found {len(out)}")
    tile = _sections(LOGO_TILE.read_text(), ("LogoTile",))
    if len(tile) != 1:
        raise ValueError(f"{LOGO_TILE.name}: expected one LogoTile section, found {len(tile)}")
    return "".join(out) + "\n" + tile[0].split("/* In a LogoStack")[0]


def minify(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    return re.sub(r";}", "}", re.sub(r": ", ":", re.sub(r" ?([{};,]) ?", r"\1", re.sub(r"\s+", " ", css)))).strip()


def split_top(text, sep):
    """``text`` cut at ``sep`` where no bracket or parenthesis is open."""
    out, depth, start = [], 0, 0
    for i, ch in enumerate(text):
        depth += ch in "([{" ; depth -= ch in ")]}"
        if ch == sep and depth == 0:
            out.append(text[start:i]); start = i + 1
    return out + [text[start:]]


def css_rules(css):
    """[(prelude, body)] of a minified sheet: a rule's declarations, or an @media's rules (as a list)."""
    rules, i = [], 0
    while i < len(css):
        j = css.index("{", i)
        depth, k = 1, j + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0); k += 1
        prelude, body = css[i:j], css[j + 1:k - 1]
        rules.append((prelude, css_rules(body) if prelude.startswith("@") else body))
        i = k
    return rules


def uses_of(scan):
    """What the surface's source (``scan``: a comma list of folders or files) writes of the primitives: {attribute:
    values},
    and "class": the .ui-* classes."""
    files = []
    for name in filter(None, scan.split(",")):
        path = ROOT / name
        files += [path] if path.is_file() else sorted(path.rglob("*"))
    text = "\n".join(file.read_text(errors="replace") for file in files if file.is_file() and file.suffix in SCANNED)
    used = {"class": set(re.findall(r"\bui-[\w-]+", text))}
    for name, value in re.findall(r'\b([a-z][\w-]*)="([^"$]*)"', text):
        used.setdefault(name, set()).add(value)
    used.setdefault("data-variant", set()).update(re.findall(r'buttonAttrs\("([\w-]+)"', text))
    for name in re.findall(r"\s(data-[\w-]+)(?=[\s>=])", text):
        used.setdefault(name, set())
    return used


def reachable(selector, used):
    """Whether a page that writes ``used`` can match ``selector``: every attribute and .ui-* class it needs is written,
    and one member of each :is() group is. :not(), :has() and :where() groups are left out of the test."""
    for group in re.findall(r":is\(((?:[^()]|\([^()]*\))*)\)", selector):
        # A member that names nothing the primitives write (another component's class) can't match.
        if not any(re.search(r'\[data-|\.ui-', member) and reachable(member, used) for member in split_top(group, ",")):
            return False
    bare = re.sub(r":(?:not|is|has|where)\((?:[^()]|\([^()]*\))*\)", "", selector)
    for name in re.findall(r"\[(data-[\w-]+)\]", bare):
        if name not in used:
            return False
    for name, op, value in re.findall(r'\[([\w-]+)(\^?=)"([^"]*)"\]', bare):
        if not any(v == value if op == "=" else v.startswith(value) for v in used.get(name, set())):
            return False
    return all(cls in used["class"] for cls in re.findall(r"\.(ui-[\w-]+)", bare))


def prune(rules, used):
    out = []
    for prelude, body in rules:
        if prelude.startswith("@"):
            kept = prune(body, used)
            if kept:
                out.append((prelude, kept))
            continue
        selectors = [x for x in split_top(prelude, ",") if reachable(x, used)]
        if selectors:
            out.append((",".join(selectors), body))
    return out


def render(rules):
    return "".join(f"{p}{{{render(b) if isinstance(b, list) else b}}}" for p, b in rules)


def primitives_css(tokens, scan=None, reads=()):
    """The rules of the primitives' sections and the names they read that the token region doesn't write (the app's
    semantic names, from ui_vars).
    With ``scan``, only the rules that surface's source can reach, and the names those read.
    ``reads``: the app's names the surface's own rules read (Remote's title, --text-hero), written beside them."""
    sheet = minify(primitive_sections(PRIMITIVES_CSS.read_text()))
    if scan:
        sheet = render(prune(css_rules(sheet), uses_of(scan)))
    own = {line.split(":", 1)[0][2:] for line in _vars(tokens, "light") + _vars(tokens, "dark") + _common(tokens)}
    schemes = {name: {line.split(":", 1)[0][2:]: line.split(":", 1)[1].strip().rstrip(";")
                      for line in ui_vars(tokens, name)} for name in ("light", "dark", "common")}
    wanted, todo = set(), set(re.findall(r"var\(--([\w-]+)", sheet)) | set(reads)
    while todo:
        name = todo.pop()
        if name not in wanted:
            wanted.add(name)
            todo |= set(re.findall(r"var\(--([\w-]+)", " ".join(s.get(name, "") for s in schemes.values())))

    def block(*names):
        merged = {k: v for n in names for k, v in schemes[n].items() if k in wanted and k not in own}
        return "".join(f"--{k}:{v};" for k, v in merged.items())

    light = block("common", "light")
    dark = {k: v for k, v in schemes["dark"].items() if k in wanted and k not in own and schemes["light"].get(k) != v}
    head = f":root{{{light}}}" + (
        f"@media (prefers-color-scheme: dark){{:root{{{''.join(f'--{k}:{v};' for k, v in dark.items())}}}}}" if dark
        else "")
    return head + "@layer components{" + sheet + "}"


def primitive_regions(text, tokens):
    if not PRIMITIVES_CSS.exists():  # the public tree has no dashboard/
        return text

    def region(match):
        options = dict(option.split("=", 1) for option in match.group("options").split())
        begin = match.group(0)[:match.group(0).index("*/") + 2]
        return f"{begin}\n{primitives_css(tokens, options.get('scan'), reads)}\n{P_END}"

    reads = set(re.findall(r"var\(--([\w-]+)", P_REGION.sub("", REGION.sub("", text))))
    return P_REGION.sub(region, text)


def docs_json(text, tokens):
    """docs.json with the theme's colours set, and nothing else in the file touched."""
    light, dark = resolve(tokens["color"]["light"]), resolve(tokens["color"]["dark"])
    # Mintlify: primary is links and accents on light pages, light the same on dark pages, dark the buttons.
    colors = {"primary": light["violet-text"], "light": dark["violet-text"], "dark": light["violet-solid"]}
    for key, value in colors.items():
        text = re.sub(r'("colors": \{[^}]*?"' + key + r'": )"#[0-9A-Fa-f]{6}"', rf'\1"{value}"', text, count=1)
    for key, value in (("light", light["paper"]), ("dark", dark["paper"])):
        text = re.sub(r'("background": \{\s*"color": \{[^}]*?"' + key + r'": )"#[0-9A-Fa-f]{6}"', rf'\1"{value}"',
                      text, count=1)
    return text


# The docs' faces: docs.json names Mobster Sans for Mintlify, which declares it at a single weight; these declare each
# face over its whole range (tokens.json › font), from docs/fonts (the COPIES above).
def docs_faces(tokens):
    return "".join(f'@font-face{{font-family:"{font["name"]}";src:url("/fonts/{font["file"]}") format("woff2");'
                   f'font-weight:{font["weights"][0]} {font["weights"][-1]};font-display:swap}}'
                   for font in (tokens["font"]["sans"], tokens["font"]["mono"]))


# Mintlify draws its own chrome and prose from one grey ramp, --gray-50 to --gray-950 as "R G B" channels (it writes
# rgb(var(--gray-700)) and rgb(var(--gray-950) / .05)), light pages from the dark end and dark pages from the light
# end. Its ramp leans to the theme's primary, our violet. A `brand:tokens as=mintlify` region gives each step the brand
# grey that does that step's job in each appearance: reading copy (light 700, dark 400) is ink-2, titles and strong
# text ink, icons and quiet text ink-3 and ink-4, hairlines line and line-strong. Light under :root:not(.dark) and dark
# under :root.dark, so the region outranks Mintlify's own :root block wherever the two land on the page.
MINTLIFY_GREYS = {
    "light": {50: "card", 100: "sunken", 200: "line", 300: "line-strong", 400: "ink-4", 500: "ink-3", 600: "ink-2",
              700: "ink-2", 800: "ink", 900: "ink", 950: "ink"},
    "dark": {50: "ink", 100: "ink", 200: "ink", 300: "ink", 400: "ink-2", 500: "ink-3", 600: "ink-4",
             700: "line-strong", 800: "line", 900: "surface", 950: "sunken"},
}


# Mintlify's code blocks use its "css-variables" Shiki theme (docs.json styling.codeblocks), which colours each token
# with a --mint-token-* name: each gets the colour of the code role (tokens.json "code") that does its job, so the docs
# highlight as mobster.dev and the app do. Shiki gives a YAML or JSON key the keyword's name and a plain YAML value the
# string expression's. Mintlify's guide names the text --mint-color-text; its renderer reads --mint-foreground.
MINTLIFY_CODE = {"color-text": "text", "foreground": "text", "token-constant": "text", "token-parameter": "text",
                 "token-function": "text",
                 "token-keyword": "keyword", "token-link": "keyword", "token-string": "string",
                 "token-string-expression": "string", "token-comment": "muted", "token-punctuation": "muted"}


def mintlify_greys(tokens):
    blocks = []
    for scheme, selector in (("light", ":root:not(.dark)"), ("dark", ":root.dark")):
        palette = resolve(tokens["color"][scheme])
        steps = "".join(f"--gray-{step}:{' '.join(str(c) for c in _rgb(palette[name]))};"
                        for step, name in MINTLIFY_GREYS[scheme].items())
        roles = tokens["code"]["role"]
        code = "".join(f"--mint-{name}:{palette[roles[role]].lower()};" for name, role in MINTLIFY_CODE.items())
        plate = palette[tokens["code"]["plate"]].lower()
        code += f"--mint-color-background:{plate};--mint-background:{plate};"
        blocks.append(f"{selector}{{{steps}{code}}}")
    return "".join(blocks)


MANIFEST = ROOT / "scripts" / "ui-manifest.json"
SECTION = re.compile(r"^  /\* ─── (.+?) ─+ \*/$", re.M)


def ui_sections(css, titles, tail):
    """The named sections of ui.css's @layer (each runs to the next section header), then its closing rules for phone
    width and reduced motion, which start at the first @media block after the last section."""
    found = list(SECTION.finditer(css))
    layer_end = css.index("\n}\n", found[-1].end())
    body = []
    for title in titles:
        for n, match in enumerate(found):
            if match.group(1).startswith(title):
                end = found[n + 1].start() if n + 1 < len(found) else layer_end
                body.append(css[match.start():end].rstrip("\n"))
                break
        else:
            raise SystemExit(f"ui-manifest.json: ui.css has no section {title!r}")
    start = css.index("  /* On a phone's width or a touch screen", found[-1].end())
    body.append(f"  /* ─── {tail} ─── */\n" + css[start:layer_end].rstrip("\n"))
    return "\n\n".join(body)


def ui_files():
    """[(path, text)] for the primitives mobster.dev copies (scripts/ui-manifest.json)."""
    manifest = json.loads(MANIFEST.read_text())
    out = []
    for name in manifest["files"]:
        text = (ROOT / manifest["from"] / name).read_text()
        note = (
            f"Generated from {manifest['from']}/{name} by scripts/gen_brand_tokens.py. Don't edit: change the source "
            "and run it.")
        # Next renders the site's pages on the server: a file that uses hooks is a client component there (the app's
        # Vite build has no such split).
        client = '"use client"\n' if re.search(r"\buse(State|Effect|Ref|Layout|Callback|Memo)\w*\(", text) else ""
        out.append((ROOT / manifest["to"] / name,
                    (f"/* {note} */\n" if name.endswith(".css") else f"// {note}\n") + client + text))
    css = manifest["css"]
    head = (f"/* Generated from {css['from']} by scripts/gen_brand_tokens.py (scripts/ui-manifest.json). Don't edit: "
            "change the "
            "source and run it.\n   The primitives' look, keyed on [data-slot][data-variant][data-size]; the tokens "
            "they read are "
            "the `brand:tokens as=ui` regions of styles/tokens.css. */\n")
    sections = ui_sections((ROOT / css["from"]).read_text(), css["sections"], css["tail"])
    out.append((ROOT / css["to"], head + "@layer components {\n" + sections + "\n}\n"))
    return out


def tracked_files():
    try:
        names = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, check=True).stdout
        return [ROOT / name for name in names.decode().split("\0") if name]
    except (OSError, subprocess.CalledProcessError):
        return [path for path in ROOT.rglob("*") if path.is_file() and ".git" not in path.parts
                and "node_modules" not in path.parts]


def plan(tokens):
    """[(path, new bytes)] for every output this tree has."""
    out = [(BRAND_PY, brand_py(tokens).encode())]
    if FONTS.is_dir():
        out.append((FONTS_PY, fonts_py(tokens).encode()))
    if DOCS_JSON.exists():
        out.append((DOCS_JSON, docs_json(DOCS_JSON.read_text(), tokens).encode()))
    if LOGO.is_dir():
        out += [(LOGO / name, text.encode()) for name, text in logo_files(tokens).items()]
    if FAVICON.is_dir():
        out += [(FAVICON / name, text.encode()) for name, text in favicon_files(tokens).items()]
    if SITE_GEOMETRY.parent.is_dir():
        out.append((SITE_GEOMETRY, brand_geometry_ts().encode()))
        # Safari's pinned-tab mask: the mark in one colour; the page names the colour.
        out.append((ROOT / "site" / "public" / "safari-pinned-tab.svg",
                    (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">'
                     f'<path d="{mark_path()}"/></svg>\n').encode()))
    if MANIFEST.exists() and (ROOT / "dashboard" / "src").is_dir() and (ROOT / "site" / "app").is_dir():
        out += [(path, text.encode()) for path, text in ui_files()]
    copies = {ROOT / copy for copy, _ in COPIES} | {ROOT / path for path in PAGES}
    for path in tracked_files():
        if path.suffix in {".css", ".html", ".rs", ".ts", ".mdx"} and path.exists() and path not in copies:
            text = path.read_text(errors="replace")
            if "/* brand:tokens" in text or P_BEGIN in text:
                out.append((path, regions(primitive_regions(text, tokens), tokens, path).encode()))
    planned = dict(out)
    for copy, source in COPIES:
        surface = ROOT / Path(copy).parts[0]
        copy, source = ROOT / copy, ROOT / source
        if not surface.exists():
            continue
        if source.exists():
            out.append((copy, planned.get(source) or source.read_bytes()))
        elif (ROOT / Path(source.relative_to(ROOT)).parts[0]).exists():
            # The source's own folder is here, so the file is deleted, not absent from a partial tree: fail, never skip.
            raise MissingSource(f"{source.relative_to(ROOT)} is missing; {copy.relative_to(ROOT)} is a copy of it")
    if PAGE_STYLE.exists() and (ROOT / "services").exists() and FONTS.is_dir():
        style = (planned.get(PAGE_STYLE) or PAGE_STYLE.read_bytes()).decode()
        for path, (title, lead) in PAGES.items():
            out.append((ROOT / path, page(style, title, lead, planned).encode()))
    return out


def _data_url(kind, data):
    return f"data:{kind};base64,{base64.b64encode(data).decode()}"


def _picture(cls, base, size, planned):
    """A brand file, light and dark, as the scheme picks it: as this run writes it, or as it is on disk."""
    light, dark = (planned.get(ROOT / f"{base}-{theme}.svg") or (ROOT / f"{base}-{theme}.svg").read_bytes()
                   for theme in ("light", "dark"))
    return (f'<picture class="{cls}"><source srcset="{_data_url("image/svg+xml", dark)}" '
            f'media="(prefers-color-scheme: dark)"><img src="{_data_url("image/svg+xml", light)}" alt="" '
            f'width="{size}" height="{size}"></picture>')


def page(style, title, lead, planned):
    """One of the license API's pages, self-contained."""
    face = _data_url("font/woff2", (FONTS / "google-sans-flex.woff2").read_bytes())
    style = style.replace('url("/assets/fonts/mobster-sans.woff2")', f'url("{face}")').strip()
    return PAGE.format(title=title, lead=lead, style=style, mark=_picture("mark", "docs/brand/logo/mark", 28, planned))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], allow_abbrev=False)
    parser.add_argument("--check", action="store_true", help="list stale copies instead of writing them")
    parser.add_argument("--png", action="store_true", help="also draw the PNGs from the mark's SVGs")
    args = parser.parse_args(argv)
    check = args.check
    if args.png and not check:
        render_rasters(load())
    stale = []
    try:
        planned = plan(load())
    except MissingSource as error:
        print(f"missing source: {error}")
        return 1
    for path, data in planned:
        if path.exists() and path.read_bytes() == data:
            continue
        stale.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    for path in stale:
        print(("differs from docs/brand/tokens.json: " if check else "wrote ") + str(path))
    if check and stale:
        print("run: python3 scripts/gen_brand_tokens.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
