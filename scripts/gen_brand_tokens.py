def _n(value):
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def _corner(cx, cy, u, v, r, s):
    """Figma's smoothed corner at (cx, cy), met along u and left along v (unit vectors): path commands from the
    point (1 + s) * r before the corner to the point as far after it."""
    p = (1 + s) * r
    arc = math.radians(90 * (1 - s))
    chord = math.sin(arc / 2) * r * math.sqrt(2)
    p34 = r * math.tan((math.pi / 2 - arc) / 4)
    c = p34 * math.cos(math.radians(45 * s))
    d = c * math.tan(math.radians(45 * s))
    b = (p - chord - c - d) / 3
    a = 2 * b

    def at(along, inward):
        return f"{_n(cx + u[0] * along + v[0] * inward)} {_n(cy + u[1] * along + v[1] * inward)}"

    out = f"L{at(-p, 0)}"
    if a + b + c > 1e-9:
        out += f"C{at(-p + a, 0)} {at(-p + a + b, 0)} {at(-p + a + b + c, d)}"
    out += f"A{_n(r)} {_n(r)} 0 0 1 {at(-d, p - a - b - c)}"
    if a + b + c > 1e-9:
        out += f"C{at(0, p - a - b)} {at(0, p - a)} {at(0, p)}"
    return out


def slab(x, y, w, h, r, s, corners, k=1.0, dx=0.0, dy=0.0):
    """One slab as a closed path, scaled by k and moved by (dx, dy), drawn clockwise."""
    x, y, w, h, r = x * k + dx, y * k + dy, w * k, h * k, r * k
    tr, br, bl, tl = corners
    for side, ends in ((w, (tl, tr)), (h, (tr, br)), (w, (br, bl)), (h, (bl, tl))):
        assert sum(ends) * (1 + s) * r <= side + 1e-9, "a corner is larger than its side"
    turns = (((x + w, y), (1, 0), (0, 1), tr), ((x + w, y + h), (0, 1), (-1, 0), br),
             ((x, y + h), (-1, 0), (0, -1), bl), ((x, y), (0, -1), (1, 0), tl))
    start = (x + (1 + s) * r, y) if tl else (x, y)
    d = f"M{_n(start[0])} {_n(start[1])}"
    for (cx, cy), u, v, rounded in turns:
        d += _corner(cx, cy, u, v, r, s) if rounded else f"L{_n(cx)} {_n(cy)}"
    return d + "Z"


